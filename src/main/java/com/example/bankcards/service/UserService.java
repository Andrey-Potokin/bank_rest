package com.example.bankcards.service;

import com.example.bankcards.dto.UserCreateRequest;
import com.example.bankcards.dto.UserResponse;
import com.example.bankcards.entity.UserRole;

/**
 * Сервис для управления пользователями системы.
 * <p>
 * Предоставляет бизнес-логику для выполнения операций с пользователями: создание новых учётных записей,
 * получение данных о пользователе по идентификатору, изменение роли пользователя и удаление учётной записи.
 * <p>
 * Все методы сервиса обеспечивают проверку данных, контроль доступа и взаимодействие с репозиторием пользователей.
 
 */
public interface UserService {

    /**
     * Создаёт нового пользователя в системе.
     * <p>
     * Принимает DTO с основными данными пользователя и пароль в открытом виде.
     * Проверяет уникальность логина, корректность данных и сохраняет нового пользователя
     * с зашифрованным паролем и ролью по умолчанию (USER).
     *
     * @param request  объект с данными пользователя (например, логин); не может быть null
     * @param password пароль пользователя в открытом виде; не может быть пустым или null
     * @return объект {@link UserResponse} с данными созданного пользователя, включая его ID и роль
     * @throws IllegalArgumentException если логин уже занят или переданы некорректные данные
     */
    UserResponse createUser(UserCreateRequest request, String password);

    /**
     * Получает информацию о пользователе по его идентификатору.
     * <p>
     * Ищет пользователя в базе данных и возвращает его данные в виде DTO.
     * Используется, например, администратором для просмотра профиля пользователя.
     *
     * @param id идентификатор пользователя, которого необходимо найти; должен быть положительным
     * @return объект {@link UserResponse} с данными пользователя
     * @throws com.example.bankcards.exception.NotFoundException если пользователь с указанным ID не найден
     */
    UserResponse getUserById(Long id);

    /**
     * Обновляет роль пользователя.
     * <p>
     * Позволяет изменить роль пользователя (например, с USER на ADMIN).
     * Может использоваться только администратором. Проверяет существование пользователя
     * и корректность переданной роли.
     *
     * @param userId идентификатор пользователя, чья роль должна быть изменена
     * @param role   новая роль пользователя; не может быть null
     * @throws com.example.bankcards.exception.NotFoundException если пользователь с указанным ID не найден
     */
    void updateRole(Long userId, UserRole role);

    /**
     * Удаляет пользователя из системы.
     * <p>
     * Операция безвозвратно удаляет учётную запись пользователя и все связанные с ней данные
     * (включая банковские карты). Может использоваться только администратором.
     *
     * @param userId идентификатор пользователя, которого необходимо удалить
     * @throws com.example.bankcards.exception.NotFoundException если пользователь с указанным ID не найден
     */
    void deleteUser(Long userId);
}