package com.example.bankcards.entity;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.Getter;

/**
 * Статус банковской карты.
 * <p>
 * Определяет текущее состояние карты в системе. Используется для управления доступом
 * к операциям с картой и отображения её состояния в интерфейсе.
 * <p>
 * Поддерживаемые статусы:
 * <ul>
 *   <li>{@link #ACTIVE} — карта активна и доступна для всех операций</li>
 *   <li>{@link #BLOCKED} — карта заблокирована пользователем или администратором</li>
 *   <li>{@link #EXPIRED} — срок действия карты истёк</li>
 * </ul>
 */
@Getter
@Schema(description = "Статус карты")
public enum CardStatus {

    /**
     * Карта активна и может использоваться в операциях.
     * <p>
     * Переводы, пополнения и списания разрешены.
     */
    @Schema(description = "Активна")
    ACTIVE("Активна"),

    /**
     * Карта заблокирована.
     * <p>
     * Все операции с картой запрещены до разблокировки.
     * Блокировка может быть инициирована пользователем или администратором.
     */
    @Schema(description = "Заблокирована")
    BLOCKED("Заблокирована"),

    /**
     * Срок действия карты истёк.
     * <p>
     * Карта автоматически переводится в этот статус при достижении даты окончания.
     * Операции запрещены. Требуется выпуск новой карты.
     */
    @Schema(description = "Срок истёк")
    EXPIRED("Срок истёк");

    /**
     * Текстовое представление статуса карты.
     * Используется для отображения в интерфейсе и логах.
     */
    @Schema(description = "Текстовое представление статуса")
    private final String value;

    /**
     * Конструктор для установки текстового значения статуса.
     *
     * @param value строковое представление статуса (например, "Активна")
     */
    CardStatus(String value) {
        this.value = value;
    }
}